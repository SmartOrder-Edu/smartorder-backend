-- 学习脚本媒体资产表：保存 TTS 音频、字幕、脚本和 Timeline 资源
CREATE TABLE IF NOT EXISTS `lesson_media_asset` (
    `id`                BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    `lesson_bundle_id`  VARCHAR(80)  NOT NULL                COMMENT '备课包业务ID',
    `scene_id`          VARCHAR(80)  NOT NULL                COMMENT '教学场景ID',
    `segment_id`        VARCHAR(80)  DEFAULT NULL            COMMENT '教学段ID',
    `provider`          VARCHAR(32)  NOT NULL DEFAULT 'xfyun' COMMENT '语音服务商',
    `provider_sid`      VARCHAR(128) DEFAULT NULL            COMMENT '服务商会话ID',
    `voice_code`        VARCHAR(128) NOT NULL                COMMENT '发音人编码',
    `speed`             INT          NOT NULL DEFAULT 50     COMMENT '语速',
    `volume`            INT          NOT NULL DEFAULT 50     COMMENT '音量',
    `pitch`             INT          NOT NULL DEFAULT 50     COMMENT '语调',
    `display_text`      TEXT         NOT NULL                COMMENT '展示文本',
    `speech_text`       TEXT         NOT NULL                COMMENT '实际播报文本',
    `text_hash`         VARCHAR(64)  NOT NULL                COMMENT '文本与发音参数摘要',
    `audio_url`         VARCHAR(512) DEFAULT NULL            COMMENT '音频访问地址',
    `script_url`        VARCHAR(512) DEFAULT NULL            COMMENT '脚本资源地址',
    `subtitle_url`      VARCHAR(512) DEFAULT NULL            COMMENT '字幕资源地址',
    `timeline_url`      VARCHAR(512) DEFAULT NULL            COMMENT 'Timeline 资源地址',
    `duration_ms`       BIGINT       DEFAULT NULL            COMMENT '音频时长，毫秒',
    `status`            VARCHAR(32)  NOT NULL DEFAULT 'pending' COMMENT '状态：pending/generating/ready/failed',
    `error_code`        VARCHAR(64)  DEFAULT NULL            COMMENT '失败错误码',
    `error_message`     TEXT         DEFAULT NULL            COMMENT '失败原因',
    `create_time`       DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_time`       DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_text_voice` (`text_hash`, `voice_code`, `speed`, `pitch`),
    KEY `idx_bundle_scene` (`lesson_bundle_id`, `scene_id`),
    KEY `idx_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='学习脚本媒体资产表';
