CREATE TABLE knowledge_chunks (
      id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT 'chunk ID，系统内部',
      user_id BIGINT NOT NULL COMMENT '所属用户ID，用于多用户数据隔离',
      knowledge_base_id BIGINT NOT NULL COMMENT '所属知识库ID，用于限定RAG检索范围',
      file_id BIGINT NOT NULL COMMENT '来源文件ID，用于追溯chunk来自哪个文件',
      document_id BIGINT NOT NULL COMMENT '来源文档ID，用于追溯chunk来自',
      chunk_index INT NOT NULL COMMENT 'chunk在当前文档中的顺序编号',
      chunk_type VARCHAR(50) DEFAULT 'text' COMMENT 'chunk类型：text=普通文本，table=表格，image_ocr=图片OCR，code=代码',
      content_preview VARCHAR(500) COMMENT 'chunk内容预览，只存前几百字，用于前端展示和调试，不存完整文本',
      content_hash VARCHAR(128) COMMENT 'chunk内容哈希，用于去重和判断是否需要重新生成',
      token_count INT COMMENT 'chunk token数量，用于控制上下文长度',
      char_count INT COMMENT 'chunk字符数量',
      page_number INT COMMENT 'chunk所在页码，用于PDF、PPT、Word引用展示',
      section_title VARCHAR(255) COMMENT 'chunk所属章节标题',
      section_level INT COMMENT '章节层级，例如1=一级标题，2=二级标题',
      title_path VARCHAR(500) COMMENT '标题路径，例如：第一章/进程管理/',
      prev_chunk_id BIGINT COMMENT '上一个chunk ID，用于上下文扩展',
      next_chunk_id BIGINT COMMENT '下一个chunk ID，用于上下文串联',
      vector_collection VARCHAR(100) DEFAULT 'rag_chunks' COMMENT '向量数据库collection名称',
      vector_id VARCHAR(100) NOT NULL COMMENT '向量数据库中的向量ID，用于从向量库取完整chunk和embedding',
      embedding_model VARCHAR(100) COMMENT '该chunk使用的向量模型名称',
      embedding_status VARCHAR(30) DEFAULT 'pending' COMMENT '向量化状态：pending=待向量化，embedding=向量化中，embedded=已向量化，failed=向量化失败',
      embedding_error TEXT COMMENT '向量化失败错误信息',
      metadata JSON COMMENT 'chunk元信息，例如表格结构、图片位置、页面坐标、标题信息',
      status VARCHAR(30) DEFAULT 'active' COMMENT 'chunk状态：active=正常，deleted=已删除',
      created_at DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
      updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间'
) COMMENT='chunk元数据表，数据库只管理chunk结构、来源、状态和向量ID，不负责主要语义检索';