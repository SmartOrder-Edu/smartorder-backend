CREATE TABLE `user`
(
    `id`              bigint(20) unsigned zerofill NOT NULL AUTO_INCREMENT COMMENT '用户ID',
    `username`        varchar(50) COLLATE utf8mb4_unicode_ci  NOT NULL COMMENT '用户名/昵称',
    `email`           varchar(100) COLLATE utf8mb4_unicode_ci NOT NULL,
    `email_verified`  tinyint                                 NOT NULL DEFAULT '0' COMMENT '邮箱是否已验证：0=未验证，1=已验证',
    `phone`           varchar(20) COLLATE utf8mb4_unicode_ci           DEFAULT NULL COMMENT '手机号',
    `password`        varchar(255) COLLATE utf8mb4_unicode_ci          DEFAULT NULL COMMENT '密码（BCrypt加密，纯第三方账号可为空）',
    `avatar_url`      varchar(500) COLLATE utf8mb4_unicode_ci          DEFAULT NULL COMMENT '头像URL',
    `gender`          tinyint                                          DEFAULT '0' COMMENT '性别：0=未设置，1=男，2=女',
    `birthday`        date                                             DEFAULT NULL COMMENT '生日',
    `bio`             varchar(500) COLLATE utf8mb4_unicode_ci          DEFAULT NULL COMMENT '个人简介',
    `role`            tinyint                                 NOT NULL DEFAULT '0' COMMENT '角色：0=学生，1=管理员，2=老师',
    `vip_level`       tinyint                                 NOT NULL DEFAULT '0' COMMENT 'VIP等级：0=普通用户',
    `vip_start_time`  datetime                                         DEFAULT NULL COMMENT 'VIP开始时间',
    `vip_expire_time` datetime                                         DEFAULT NULL COMMENT 'VIP到期时间',
    `status`          tinyint                                 NOT NULL DEFAULT '1' COMMENT '账号状态：0=禁用，1=正常',
    `is_deleted`      tinyint                                 NOT NULL DEFAULT '0' COMMENT '逻辑删除：0=正常，1=已删除',
    `create_time`     datetime                                NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `update_time`     datetime                                NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `github_id`       varchar(50) COLLATE utf8mb4_unicode_ci           DEFAULT NULL COMMENT 'GitHub 用户唯一标识',
    `github_username` varchar(100) COLLATE utf8mb4_unicode_ci          DEFAULT NULL COMMENT 'GitHub 用户名',
    `gitee_id`        varchar(50) COLLATE utf8mb4_unicode_ci           DEFAULT NULL COMMENT 'Gitee用户唯一标识',
    `gitee_username`  varchar(100) COLLATE utf8mb4_unicode_ci          DEFAULT NULL COMMENT 'Gitee用户名',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_username` (`username`),
    UNIQUE KEY `uk_email` (`email`),
    UNIQUE KEY `uk_phone` (`phone`),
    UNIQUE KEY `uk_github_id` (`github_id`),
    UNIQUE KEY `uk_gitee_id` (`gitee_id`),
    KEY               `idx_role` (`role`),
    KEY               `idx_vip_expire_time` (`vip_expire_time`),
    KEY               `idx_status_deleted` (`is_deleted`,`status`)
) ENGINE=InnoDB AUTO_INCREMENT=2076292478315012097 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='用户表';